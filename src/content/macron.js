/**
 * macron.js
 * 長音符(macron)的處理,集中在這裡一份。
 *
 * 為什麼要獨立成一支:
 * romaji.js 轉換時要拿掉長音符,splitter.js 比對舊的切分資料時
 * 也要用同一套規則(舊資料是拿掉長音符之前存的,含 ō ē)。
 * 兩邊各寫一份,哪天改了其中一邊,舊切分就會無聲無息地全部失效 ——
 * 而且那種壞法不會噴錯,只會讓使用者覺得自己的設定莫名其妙消失。
 *
 * 這支不 import 任何東西、也沒有 module-level 副作用,
 * 所以 splitter.js 可以安心用,不會把 kuroshiro 一起拖進來。
 */

/*
 * 組合用長音符 U+0304。
 *
 * 刻意用碼位而不是直接把那個字元寫進原始碼:組合字元單獨出現時
 * 在編輯器裡是看不見的,很容易在編輯或複製貼上時被弄丟,
 * 而且壞掉之後從程式碼上完全看不出來。
 */
const COMBINING_MACRON = String.fromCharCode(0x0304);

/**
 * 拿掉長音符:ā ī ū ē ō → a i u e o
 *
 * kuroshiro 預設是 Hepburn 式,長音會標成 ō / ē 這種頭上一橫的字元。
 * 那一橫在畫面上看起來就是「拼音上面多了一條線」,跟唱時只是干擾。
 *
 * 為什麼用正規化而不是逐字對照表:
 * NFD 會把 ō 拆成「o + 組合用長音符(U+0304)」,刪掉那個組合字元即可 ——
 * 五個母音、大小寫全部涵蓋,而且不管 kuroshiro 吐的是預組合字元
 * 還是組合序列都吃得到。
 *
 * **長度不變**(1 個字元換 1 個字元)。這一點是 splitter.js 能沿用
 * 舊切分的前提:切點是字母索引,長度一變索引就會落在錯的位置。
 * 改這個函式的時候務必守住這個性質。
 *
 * 代價:長音的資訊沒了(`ō` 與 `o` 變成一樣)。這是刻意的取捨 ——
 * 跟唱時要的是好讀,不是嚴謹的轉寫。
 *
 * @param {string} text
 * @returns {string}
 */
export function stripMacrons(text) {
  return text.normalize('NFD').split(COMBINING_MACRON).join('').normalize('NFC');
}

/** 長音記號 U+30FC(ー)。把前一個音拉長,本身沒有讀音。 */
const PROLONG_MARK = 'ー';

/**
 * 拿掉沒被轉換、原樣掉進羅馬拼音裡的長音記號。
 *
 * ── 什麼時候會發生 ────────────────────────────────────────────
 * 字典認得的詞不會有這個問題:「ラーメン」正確轉成 rāmen。
 * 但字典**不認識**的詞(擬聲詞、造詞、歌詞裡的玩法)會退回逐字處理,
 * 而 ー 不是假名、對不到任何羅馬字,就原樣掉出來:
 *
 *   ひゅるひゅるりーらら  →  hi yuruhyururi ー ra ra
 *                                          ^^ 這個
 *
 * 不處理的話有兩個問題:拼音裡混著一個日文符號很難讀;而且「哪些字沒轉出來」
 * 的偵測會把它標紅、叫使用者去補讀音 —— 但**它本來就沒有讀音**,
 * 那是一個做不到的要求。
 *
 * ── 為什麼是拿掉而不是把母音拉長 ──────────────────────────────
 * 為了跟既有行為一致:stripMacrons 已經把 rāmen 變成 ramen,長音的資訊
 * 本來就沒有保留。這裡若改成 hyururii,同一個概念會有兩種寫法。
 * 跟唱要的是好讀,不是嚴謹的轉寫(見上面 stripMacrons 的說明)。
 *
 * 「保留長音」這個選項有被討論過並**刻意暫緩**,不是沒想到:
 * 做法會是把 ー 換成前一個母音(hyururi ー → hyururii)。技術上可行,
 * 因為假名的羅馬字幾乎都以母音收尾。但風險是收尾不是母音的情況
 * (ん 之後的 ー、跨過空白的 ー),那時候疊出來的字會是錯的 ——
 * 而顯示錯的拼音比少一個長音更糟。
 * 之後若要做,務必先把那些邊界情況測起來再改。
 *
 * ── 注意:這支會改變字串長度 ───────────────────────────────────
 * 跟 stripMacrons 相反 —— 那支必須維持長度(手動切分的索引靠它),
 * 這支不行也不必。所以**兩者刻意分開**,不要合併成一個函式,
 * 否則會把 stripMacrons 的長度保證一起破壞掉。
 *
 * @param {string} text 轉換後的羅馬拼音
 * @returns {string}
 */
export function stripProlongMarks(text) {
  if (!text.includes(PROLONG_MARK)) return text; // 絕大多數句子走這條,不必動字串

  return text
    .split(PROLONG_MARK)
    .join('')
    .replace(/\s{2,}/g, ' ') // 拿掉之後可能留下連續空白
    .trim();
}
